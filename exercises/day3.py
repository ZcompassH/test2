x =input("what's x?")
y =input("what's y?")
z= x + y
print(z)
#上述，结果为12，因为x，y被当作string（字符串），所以结果只是字符的链接、拼接。
#可以使用int()函数将字符串转换为整数类型，识别变量为整数，就可以实现运算
z= int(x) + int(y)
print(z)
#上述即为运算方式
'''这好像也是一种注释方式
测试

'''
#测试成功
#上述运算好像变量z没有必要，因为函数可以嵌套，如下：
x =int(input("what's x?"))#函数嵌套，input()函数的返回值作为int()函数的参数
y =int(input("what's y?"))#函数嵌套也遵循从内向外
print(x + y)#将x，y定义为整形后，可以直接运算

#甚至可以简化成一行，但不建议，因为可读性差
print(int(input("what's x?")) + int(input("what's y?")))#出错概率也高


